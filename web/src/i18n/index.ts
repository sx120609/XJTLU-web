function isSupportedLocale(value: unknown): value is AppLocale {
  return typeof value === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

function readStoredLocale(): AppLocale {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    return isSupportedLocale(stored) ? stored : DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

const activeLocale = ref<AppLocale>(readStoredLocale());

function interpolate(message: string, params?: MessageParams) {
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (_match, key: string) => (
    params[key] === undefined ? `{${key}}` : String(params[key])
  ));
}

export function t(key: MessageKey, params?: MessageParams) {
  const value = messages[activeLocale.value][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return interpolate(value, params);
}

export function setLocale(locale: AppLocale, options: { persist?: boolean } = {}) {
  activeLocale.value = locale;
  document.documentElement.lang = locale;
  document.documentElement.dataset.locale = locale;
  if (options.persist !== false) {
    try { localStorage.setItem(LOCALE_STORAGE_KEY, locale); } catch { /* ignore */ }
  }
  window.dispatchEvent(new CustomEvent("kaopu-locale-changed", { detail: locale }));
}

export function initializeLocale() {
  setLocale(activeLocale.value, { persist: false });
}

export function applyAccountLocale(locale: unknown) {
  let hasDevicePreference = false;
  try { hasDevicePreference = isSupportedLocale(localStorage.getItem(LOCALE_STORAGE_KEY)); } catch { /* ignore */ }
  if (!hasDevicePreference && isSupportedLocale(locale)) setLocale(locale, { persist: false });
}

export function getActiveLocale() {
  return activeLocale.value;
}

export function localizeRouteTitle(title: unknown) {
  const source = String(title || "");
  const key = routeTitleKeys[source];
  return key ? t(key) : source;
}

